#!/usr/bin/env python3
"""Build the installable web app in docs/ from registro/index.html.

registro/index.html is the page published as a claude.ai artifact (no <html>/<head>).
This wraps it in a full document with a manifest, icons and a service worker so
it can be served from GitHub Pages and added to a phone's home screen.

Run from the repository root:  python3 tools/build_pwa.py
"""
import hashlib
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "registro" / "index.html"
OUT = ROOT / "docs"

NAME = "Registro Mensile"

src = SRC.read_text(encoding="utf-8")
# title and the artifact-only meta move into the generated <head>
body = re.sub(r"<title>.*?</title>\s*", "", src, count=1, flags=re.S)
body = re.sub(r'<meta name="claude:viewport-fit-sides"[^>]*>\s*', "", body, count=1)

version = hashlib.sha256((src + (OUT / "xlsx.full.min.js").read_text(encoding="utf-8")[:2000]).encode()).hexdigest()[:10]

head = f"""<!doctype html>
<html lang="it">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>{NAME}</title>
<meta name="description" content="Registro mensile con voci, giorni 1-31, generazione valori ed esportazione Excel.">
<meta name="theme-color" content="#eef2f5" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#0e1418" media="(prefers-color-scheme: dark)">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Registro">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icons/icon-192.png" type="image/png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<style>
:root{{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}}
body{{margin:0;font:14px/1.4 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}}
img{{max-width:100%}}
[hidden]{{display:none!important}}
</style>
<script>window.XLSX_SRC = "xlsx.full.min.js";</script>
</head>
<body>
"""

tail = """
<script>
if ("serviceWorker" in navigator) {
  window.addEventListener("load", () => navigator.serviceWorker.register("sw.js").catch(() => {}));
}
</script>
</body>
</html>
"""

OUT.mkdir(exist_ok=True)
(OUT / "index.html").write_text(head + body.strip() + "\n" + tail, encoding="utf-8")

manifest = {
    "name": NAME,
    "short_name": "Registro",
    "description": "Registro mensile con voci, giorni 1-31 ed esportazione Excel.",
    "lang": "it",
    "start_url": "./",
    "scope": "./",
    "display": "standalone",
    "orientation": "any",
    "background_color": "#eef2f5",
    "theme_color": "#1f6f9f",
    "icons": [
        {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png"},
        {"src": "icons/maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}
(OUT / "manifest.webmanifest").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

files = ["./", "index.html", "manifest.webmanifest", "xlsx.full.min.js",
         "icons/icon-192.png", "icons/icon-512.png", "icons/maskable-512.png", "icons/apple-touch-icon.png"]
sw = f"""// Generated by tools/build_pwa.py — offline cache for the installed app.
const CACHE = "registro-{version}";
const FILES = {json.dumps(files)};

self.addEventListener("install", e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith("registro-") && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
self.addEventListener("fetch", e => {{
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  // pages: network first so updates arrive, cache when offline
  if (req.mode === "navigate") {{
    e.respondWith(fetch(req).then(res => {{
      const copy = res.clone(); caches.open(CACHE).then(c => c.put("index.html", copy)); return res;
    }}).catch(() => caches.match("index.html")));
    return;
  }}
  e.respondWith(caches.match(req).then(hit => hit || fetch(req)));
}});
"""
(OUT / "sw.js").write_text(sw, encoding="utf-8")
(OUT / ".nojekyll").write_text("", encoding="utf-8")
print("built docs/ version", version)
